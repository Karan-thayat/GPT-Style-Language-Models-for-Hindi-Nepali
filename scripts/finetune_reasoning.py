#!/usr/bin/env python3
"""Finetune one pretrained model on its own language's reasoning dataset.

Starts from that language's Phase 2 checkpoint, keeps its tokenizer and
vocabulary fixed, and trains only on the synthetic comparative-reasoning data
generated by ``scripts/generate_reasoning_data.py``. The two languages never
share data, weights, or vocabulary, exactly as in Phase 2.

Usage::

    python scripts/finetune_reasoning.py --language hi \\
        --checkpoint hindi/checkpoints/checkpoint_best.pt \\
        --tokenizer hindi/tokenizer/hi_unigram_8000.model

The finetuned checkpoint is written in the same resume-capable format as
pretraining, so an interrupted run continues rather than restarting.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

import torch  # noqa: E402

from lma.reasoning.finetune import (  # noqa: E402
    FinetuneConfig,
    ReasoningDataset,
    ReasoningFinetuner,
    load_pretrained,
)
from lma.utils.logging_utils import setup_logging, write_json  # noqa: E402

LANGUAGES = {"hi": ("hindi", "Model H"), "ne": ("nepali", "Model L")}


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--language", required=True, choices=sorted(LANGUAGES))
    parser.add_argument("--checkpoint", required=True, type=Path,
                        help="Phase 2 pretrained checkpoint to start from")
    parser.add_argument("--tokenizer", required=True, type=Path)
    parser.add_argument("--data-dir", type=Path, default=None,
                        help="Directory holding the reasoning JSONL splits")
    parser.add_argument("--out-dir", type=Path, default=None,
                        help="Where finetuned checkpoints are written")
    parser.add_argument("--epochs", type=int, default=3)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--learning-rate", type=float, default=5e-5)
    parser.add_argument("--device", default=None)
    parser.add_argument("--no-resume", action="store_true",
                        help="Start fresh instead of continuing from a checkpoint")
    return parser.parse_args()


def load_split(data_dir: Path, language: str, split: str) -> list[dict]:
    """Read one reasoning split from its JSONL file."""
    path = data_dir / f"{language}_reasoning_{split}.jsonl"
    if not path.exists():
        raise SystemExit(
            f"missing {path}\nRun: python scripts/generate_reasoning_data.py "
            f"--language {language}"
        )
    with path.open("r", encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def main() -> int:
    """Finetune one model and record the run."""
    args = parse_args()
    directory, label = LANGUAGES[args.language]

    logger = setup_logging(
        REPO_ROOT / directory / "logs", name=f"finetune_{args.language}"
    )

    data_dir = args.data_dir or (REPO_ROOT / directory / "data" / "reasoning")
    out_dir = args.out_dir or (REPO_ROOT / directory / "checkpoints_finetuned")
    device = args.device or ("cuda" if torch.cuda.is_available() else "cpu")

    import sentencepiece as spm

    tokenizer = spm.SentencePieceProcessor(model_file=str(args.tokenizer))

    logger.info("Finetuning %s (%s)", label, args.language)
    logger.info("  pretrained checkpoint: %s", args.checkpoint)
    logger.info("  device: %s", device)

    model, payload = load_pretrained(args.checkpoint, device)
    logger.info("  parameters: %s", f"{model.num_parameters():,}")
    logger.info("  pretrained to step: %s", f"{payload.get('step', 0):,}")

    config = FinetuneConfig(
        batch_size=args.batch_size,
        epochs=args.epochs,
        learning_rate=args.learning_rate,
    )

    train_rows = load_split(data_dir, args.language, "train")
    val_rows = load_split(data_dir, args.language, "validation")
    train_data = ReasoningDataset(train_rows, tokenizer, config.max_length)
    val_data = ReasoningDataset(val_rows, tokenizer, config.max_length)

    logger.info(
        "  data: %d train, %d validation (%d skipped)",
        len(train_data),
        len(val_data),
        train_data.skipped + val_data.skipped,
    )

    finetuner = ReasoningFinetuner(
        model, train_data, val_data, config, out_dir, device=device
    )
    state = finetuner.train(resume=not args.no_resume)

    record = {
        "language": args.language,
        "model": label,
        "pretrained_checkpoint": str(args.checkpoint),
        "pretrained_step": payload.get("step"),
        "parameters": model.num_parameters(),
        "model_config": model.config.to_dict(),
        "finetune_config": config.to_dict(),
        "steps": state.step,
        "epochs": state.epoch,
        "best_val_loss": state.best_val_loss,
        "wall_seconds": round(state.wall_seconds, 1),
        "train_data": train_data.statistics(),
        "val_data": val_data.statistics(),
        "history": state.history,
        "checkpoint_dir": str(out_dir),
    }
    write_json(REPO_ROOT / directory / "reports" / "finetune_record.json", record)

    logger.info("\nFinetuning complete.")
    logger.info("  best validation loss: %.4f", state.best_val_loss)
    logger.info("  checkpoints in %s", out_dir)
    logger.info("  wrote %s/reports/finetune_record.json", directory)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
